"""G9 S1–S22: for every Settings switch, the code that reads its value outside the settings UI
(the "real effect") and the tests that exercise it. Static map, regenerated from code.

Writes docs/evidence/round3/settings-effects.md. Run from the repo root.
"""
import os, re, subprocess

MAIN = "app/src/main/java/dev/asfakul/yumeiro"
SETTINGS_UI = "ui/screens/settings/"
TOGGLE = re.compile(r'SettingsToggleRow\(\s*"((?:[^"\\]|\\.)*)"(.*?)"(setting_[a-z0-9_]+|[a-z0-9_]+_toggle|[a-z0-9_]+)"\s*(?:,|\))', re.S)
SETTER = re.compile(r'([A-Z][A-Za-z0-9]+)\.(set[A-Z][A-Za-z0-9]*)\(')


def rg(pattern, paths, extra=()):
    r = subprocess.run(["rg", "-n", "--no-heading", *extra, pattern, *paths], capture_output=True, text=True)
    return [l for l in r.stdout.splitlines() if l.strip()]


def find_object_file(obj):
    hits = rg(rf"^(internal |private )?(object|class) {obj}\b", [MAIN], ["-l"])
    return hits[0].split(":")[0] if hits else None


def setter_targets(path, setter):
    """State names a setter writes: `_x.value = …`, `x.value = …`, `putX("key"`."""
    s = open(path, encoding="utf-8").read()
    m = re.search(rf"fun {setter}\([^)]*\)[^{{=]*(=|\{{)", s)
    if not m:
        return [], []
    body = s[m.end(): m.end() + 900]
    if m.group(1) == "{":
        depth, j = 1, 0
        while j < len(body) and depth:
            depth += {"{": 1, "}": -1}.get(body[j], 0)
            j += 1
        body = body[:j]
    else:
        body = body.split("\n    fun ")[0]
    flows = sorted(set(re.findall(r"\b_?([a-z][A-Za-z0-9]*)\.value\s*=", body)))
    keys = sorted(set(re.findall(r'put[A-Z][a-z]+\(\s*([A-Z_]+|"[a-z0-9_]+")', body)))
    return flows, keys


rows = []
for d, _, files in os.walk(MAIN):
    for f in sorted(files):
        if not f.endswith(".kt"):
            continue
        p = os.path.join(d, f)
        s = open(p, encoding="utf-8").read()
        for m in TOGGLE.finditer(s):
            title, mid, tag = m.group(1), m.group(2), m.group(3)
            line = s.count("\n", 0, m.start()) + 1
            sm = SETTER.search(mid)
            obj, setter = (sm.group(1), sm.group(2)) if sm else (None, None)
            readers, tests, state = [], [], ""
            if obj:
                of = find_object_file(obj)
                flows, keys = setter_targets(of, setter) if of else ([], [])
                state = ", ".join(flows + keys)
                names = [fl for fl in flows] or [setter[3].lower() + setter[4:]]
                pat = rf"\b{obj}\.({'|'.join(re.escape(n) for n in names)})\b"
                for h in rg(pat, [MAIN]):
                    rel = os.path.relpath(h.split(":")[0], MAIN)
                    if rel.startswith(SETTINGS_UI) or rel == os.path.relpath(of or "", MAIN):
                        continue
                    readers.append(f"{rel}:{h.split(':')[1]}")
                # Reads inside the owner object itself (e.g. a getter used by workers) count too.
                if of:
                    own = [h for h in rg(rf"\b({'|'.join(names)})\.value\b|\b({'|'.join(names)})\b", [of]) if "fun set" not in h and ".value =" not in h]
                    if own and not readers:
                        readers.append(f"{os.path.relpath(of, MAIN)} (own reads: {len(own)})")
                tpat = rf"{obj}\.({setter}|{'|'.join(names)})\b|\"{tag}\""
                for h in rg(tpat, ["app/src/test", "app/src/androidTest"], ["-l"]):
                    tests.append(os.path.basename(h).replace(".kt", ""))
            rows.append((tag, title, f"{os.path.relpath(p, MAIN)}:{line}", f"{obj}.{setter}" if obj else "(inline)", state,
                         sorted(set(readers)), sorted(set(tests))))

with open("docs/evidence/round3/settings-effects.md", "w", encoding="utf-8") as o:
    o.write("# Settings switches: real effect and tests (G9 S1–S22)\n\n")
    o.write("Generated by `scripts/settings-effects.py`. \"Read by\" = code outside the settings UI that reads the "
            "value the switch writes (the effect). \"Tests\" = test classes that call the setter, read the value "
            "or tap the switch tag. Every switch persisting across a kill: `SettingsWalkDeviceTest` (31/31, "
            "run 43880703410).\n\n")
    o.write(f"{len(rows)} switches.\n\n| Tag | Title | Row | Setter | Writes | Read by (effect) | Tests |\n|---|---|---|---|---|---|---|\n")
    for tag, title, site, setter, state, readers, tests in rows:
        rd = "<br>".join(readers[:6]) + (f"<br>+{len(readers) - 6} more" if len(readers) > 6 else "") if readers else "**none found**"
        o.write(f"| `{tag}` | {title} | {site} | `{setter}` | {state} | {rd} | {', '.join(tests) or '—'} |\n")
none = [r for r in rows if not r[5]]
untested = [r for r in rows if not r[6]]
print(len(rows), "switches;", len(none), "without a reader:", [r[0] for r in none])
print(len(untested), "without a test:", [r[0] for r in untested])
