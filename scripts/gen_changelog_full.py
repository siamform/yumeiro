#!/usr/bin/env python3
"""Builds docs/release-2.1/CHANGELOG-FULL.md from the two ledgers (re-run after every ledger change)."""
import subprocess
def rows(path):
    out=[];hdr=None;sec=''
    for line in open(path):
        if line.startswith('#'): sec=line.strip('# \n')
        if not line.startswith('|'): continue
        cells=[c.strip() for c in line.strip().strip('|').split('|')]
        if set(cells[0])<=set('-: '): continue
        if cells[0] in ('ID','Status'): hdr=cells; continue
        if hdr: d=dict(zip(hdr,cells)); d['_sec']=sec; out.append(d)
    return out
head=subprocess.run(['git','rev-parse','--short=8','HEAD'],capture_output=True,text=True).stdout.strip()
o=['# Yumeiro full changelog, 2.0.0 to 2.1.0 (evidence edition)','',
f'Generated by scripts/gen_changelog_full.py from docs/MAJOR-BUGS-AND-FEATURES-2.x.md and docs/BUGS-AND-FIXES-2.0.0.md at r15-stability {head}.',
'Every status names its proof: a GitHub Actions run ID on https://github.com/siamform/yumeiro/actions/runs/<id>.',
'"Fail-before" = the new test failed on the old code; "pass-after" = it passed on the fix. User wording: CHANGELOG.md.','',
'## Part 1: the 2.x must-do list (status per item)','']
cur=None
for r in rows('docs/MAJOR-BUGS-AND-FEATURES-2.x.md'):
    if 'Meaning' in r: continue
    if r['_sec']!=cur:
        cur=r['_sec']; o+=['',f'### {cur}','','| ID | Item | Status |','|---|---|---|']
    item=r.get('Problem') or r.get('Feature') or r.get('Bug') or r.get('Bug / feature','')
    st=r.get('Status',''); miss=r.get('Missing (must do)','')
    if miss and miss not in ('—','-'): st+=f' — still to do: {miss}'
    o.append(f"| {r['ID']} | {item} | {st} |")
o+=['','## Part 2: every bug and fix since 2.0.0 (the ledger)','','| ID | Bug or finding | Fix commit | Status and evidence |','|---|---|---|---|']
for r in rows('docs/BUGS-AND-FIXES-2.0.0.md'):
    vals=[v for k,v in r.items() if k not in('ID','_sec')]
    bug=r.get('Bug',vals[0] if vals else ''); commit=r.get('Fix commit',''); st=r.get('Status','') or ' '.join(vals[1:])
    o.append(f"| {r['ID']} | {bug} | {commit} | {st} |")
open('docs/release-2.1/CHANGELOG-FULL.md','w').write('\n'.join(o)+'\n')
print(len(o))
