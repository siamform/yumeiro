package dev.asfakul.yumeiro.youtube

import dev.asfakul.yumeiro.youtube.YtCookiePaste.Format
import dev.asfakul.yumeiro.youtube.YtCookiePaste.Result
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class YtCookiePasteTest {
    // Fake values only.
    private val header = "VISITOR_INFO1_LIVE=v1; SID=sid1; HSID=h1; SAPISID=sap1; __Secure-3PSID=p3"

    private fun ok(r: Result): Result.Ok { assertTrue("expected Ok, got $r", r is Result.Ok); return r as Result.Ok }

    @Test fun `raw header value with or without the Cookie prefix`() {
        val a = ok(YtCookiePaste.parse(header))
        assertEquals(Format.HEADER, a.format)
        assertEquals("sap1", YtAccount.sapisid(a.cookie))
        val b = ok(YtCookiePaste.parse("Cookie: $header\n"))
        assertEquals(a.cookie, b.cookie)
        assertEquals(5, b.count)
    }

    @Test fun `curl command from developer tools`() {
        val b = ok(YtCookiePaste.parse("curl 'https://www.youtube.com/robots.txt' \\\n  -H 'accept: */*' \\\n  -b '$header' \\\n  -H 'user-agent: x'"))
        assertEquals(Format.CURL, b.format)
        assertEquals("sid1", YtAccount.cookieMap(b.cookie)["SID"])
        val h = ok(YtCookiePaste.parse("curl \"https://www.youtube.com/\" -H \"Cookie: $header\""))
        assertEquals("sap1", YtAccount.sapisid(h.cookie))
    }

    @Test fun `netscape cookies txt keeps only youtube domains`() {
        val txt = """
            # Netscape HTTP Cookie File
            # This file is generated by Get cookies.txt LOCALLY.
            .youtube.com	TRUE	/	TRUE	1830000000	SID	sid1
            #HttpOnly_.youtube.com	TRUE	/	TRUE	1830000000	__Secure-3PSID	p3
            .youtube.com	TRUE	/	TRUE	1830000000	SAPISID	sap1
            .google.com	TRUE	/	TRUE	1830000000	NID	google-only
        """.trimIndent()
        val r = ok(YtCookiePaste.parse(txt))
        assertEquals(Format.NETSCAPE, r.format)
        val m = YtAccount.cookieMap(r.cookie)
        assertEquals(setOf("SID", "__Secure-3PSID", "SAPISID"), m.keys)
    }

    @Test fun `json export from cookie extensions`() {
        val json = """[
            {"domain":".youtube.com","name":"SID","value":"sid1","path":"/"},
            {"domain":".youtube.com","name":"SAPISID","value":"sap1"},
            {"domain":"accounts.google.com","name":"LSID","value":"nope"}
        ]"""
        val r = ok(YtCookiePaste.parse(json))
        assertEquals(Format.JSON, r.format)
        assertNull(YtAccount.cookieMap(r.cookie)["LSID"])
    }

    @Test fun `archivetune token text`() {
        val token = "***INNERTUBE COOKIE*** =$header\n***VISITOR DATA*** =Cgt4\n***DATASYNC ID*** =123||\n***ACCOUNT NAME*** =Me"
        val r = ok(YtCookiePaste.parse(token))
        assertEquals(Format.ARCHIVETUNE, r.format)
        assertEquals("sap1", YtAccount.sapisid(r.cookie))
        assertNull(YtAccount.cookieMap(r.cookie)["***VISITOR DATA***"])
    }

    @Test fun `signed out or empty input is rejected with a helpful message`() {
        assertTrue(YtCookiePaste.parse("   ") is Result.Error)
        val r = YtCookiePaste.parse("VISITOR_INFO1_LIVE=v; PREF=f6=40")
        assertTrue((r as Result.Error).message.contains("not signed in"))
        assertTrue(YtCookiePaste.parse("hello world") is Result.Error)
        assertTrue(YtCookiePaste.parse("x".repeat(300_000)) is Result.Error)
    }

    @Test fun `youtube domain check`() {
        assertTrue(YtCookiePaste.isYouTube(".youtube.com"))
        assertTrue(YtCookiePaste.isYouTube("music.youtube.com"))
        assertFalse(YtCookiePaste.isYouTube("notyoutube.com"))
        assertFalse(YtCookiePaste.isYouTube(".google.com"))
    }

    @Test fun `signed-in marker on the account page`() {
        assertEquals(true, YtCookiePaste.pageLooksSignedIn("ytcfg.set({\"LOGGED_IN\":true,\"X\":1})"))
        assertEquals(false, YtCookiePaste.pageLooksSignedIn("{\"LOGGED_IN\":false}"))
        assertNull(YtCookiePaste.pageLooksSignedIn("<html>consent</html>"))
    }
}
